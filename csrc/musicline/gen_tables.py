"""Turn NostalgicPlayer's Musicline tables (Tables.cs, MIT) into a C++ header.

    gen_tables.py <Tables.cs> <mline_tables.h>

The tables are the ones of the original Musicline replayer: the pitch table, the
LFO waves, the filter and resonance coefficients and the "sizer" tables of the
phase effect. They are data, 300 kB of it, so they are fetched with the rest of
NostalgicPlayer by tools/build-musicline.sh and not kept in this repository.
"""
import re
import sys

CTYPE = {"sbyte": "int8_t", "byte": "uint8_t", "ushort": "uint16_t", "short": "int16_t"}
# name in Tables.cs -> (name here, number of entries it must have)
WANTED = {
    "Sine": ("Sine", 128), "DownRamp": ("DownRamp", 128), "Sawtooth": ("Sawtooth", 128),
    "Square": ("Square", 128), "PtVibratoTable": ("PTVibratoTable", 32),
    "PalPitchTable": ("PalPitchTable", 1984),   # 32 entries for notes below zero, then the table
    "ResonanceList": ("ResonanceList", 256), "ResampleList": ("ResonanceAmpList", 256),
    "FilterList": ("FilterList", 256), "ResonanceFilterList": ("ResFilterList", 256),
    "SizerOffset16": ("SizerOffset16", 15), "SizerOffset32": ("SizerOffset32", 31),
    "SizerOffset64": ("SizerOffset64", 63), "SizerOffset128": ("SizerOffset128", 127),
    "SizerOffset256": ("SizerOffset256", 255),
    "SizerTable16": ("SizerTable16", 120), "SizerTable32": ("SizerTable32", 496),
    "SizerTable64": ("SizerTable64", 2016), "SizerTable128": ("SizerTable128", 8128),
    "SizerTable256": ("SizerTable256", 32640),
}


def main() -> int:
    src = open(sys.argv[1], encoding="utf-8-sig").read()
    out = ["// Generated by gen_tables.py from NostalgicPlayer's Tables.cs. Do not edit.",
           "#pragma once", "#include <cstdint>", "namespace mline { namespace tab {"]
    found = set()
    for m in re.finditer(r"static readonly (\w+)\[\] (\w+)\s*=\s*\[(.*?)\];", src, re.S):
        ctype, name, body = m.group(1), m.group(2), m.group(3)
        if name not in WANTED:
            continue
        body = re.sub(r"//[^\n]*", "", body)
        values = [int(v, 0) for v in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", body)]
        cname, count = WANTED[name]
        if len(values) != count:
            print(f"{name}: {len(values)} entries, expected {count}", file=sys.stderr)
            return 1
        found.add(name)
        out.append(f"static const {CTYPE[ctype]} {cname}[{count}] = {{")
        for i in range(0, count, 16):
            out.append("  " + ",".join(str(v) for v in values[i:i + 16]) + ",")
        out.append("};")
    missing = set(WANTED) - found
    if missing:
        print("tables missing from Tables.cs: " + ", ".join(sorted(missing)), file=sys.stderr)
        return 1
    out.append("}}")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
